/// The two lists this capability prestages.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct CacheSettings {
  /// Binary caches to fetch from.
  pub substituters:        Vec<String>,
  /// Keys whose signatures those caches' paths must carry.
  pub trusted_public_keys: Vec<String>,
}

impl CacheSettings {
  /// True when there is nothing worth writing.
  #[must_use]
  pub const fn is_empty(&self) -> bool {
    self.substituters.is_empty() && self.trusted_public_keys.is_empty()
  }
}

/// A [`CacheSettings`] plus the attribute path that produced it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DiscoveredSettings {
  /// The attribute path that evaluated, for the status envelope and the
  /// receipt. Naming it is what makes a surprising answer debuggable.
  pub attr_path: String,
  /// What it said.
  pub settings:  CacheSettings,
}

/// Split a `toString`ed Nix list back into its elements.
fn split_words(raw: &str) -> Vec<String> {
  raw.split_whitespace().map(str::to_owned).collect()
}

