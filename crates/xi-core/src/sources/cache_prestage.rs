/// Knobs that change what a prestage is willing to do.
#[derive(Debug, Clone, Copy, Default)]
pub struct PrestageOptions {
  /// Skip the HTTPS key check and take the flake's key list on faith.
  ///
  /// For airgapped setups and for caches that serve no metadata
  /// endpoint. Prints a stderr warning naming every key it waves
  /// through, because a silent bypass of a code-signing check is the
  /// kind of thing that should be noisy.
  pub trust_declared_keys: bool,
}

/// One scope's prestage, with every outside effect injected.
///
/// Holding the three traits and the path table together is what lets
/// the whole capability be driven from a test with no `nix`, no network
/// and no `/etc`.
pub struct Prestage<'a> {
  /// Which half of the machine.
  pub scope:          Scope,
  /// Where the files live.
  pub paths:          ConfPaths,
  /// `ScopePaths::state_dir` for this scope - where the sources lock
  /// lives. Named explicitly rather than re-derived from `scope` inside
  /// [`Prestage::run`]: `ScopePaths::resolve` reads the process
  /// environment and falls back to real system paths
  /// (`/var/lib/xi/state`), which a test's `Scope::System` fixture must
  /// never touch.
  pub lock_state_dir: PathBuf,
  /// How to read flake attributes.
  pub reader:         &'a dyn AttrReader,
  /// How to check declared keys.
  pub advertiser:     &'a dyn KeyAdvertiser,
  /// How to make the daemon re-read its config.
  pub reload:         &'a dyn DaemonReload,
}

impl fmt::Debug for Prestage<'_> {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    f.debug_struct("Prestage")
      .field("scope", &self.scope)
      .field("paths", &self.paths)
      .finish_non_exhaustive()
  }
}

impl Prestage<'_> {
  /// The real wiring for `scope`: `nix eval`, HTTPS, systemd.
  #[must_use]
  pub fn live(scope: Scope) -> LiveParts {
    LiveParts {
      scope,
      paths: ConfPaths::resolve(scope),
      lock_state_dir: ScopePaths::resolve(scope).state_dir,
      reader: NixAttrReader,
      advertiser: HttpsKeyAdvertiser,
      systemctl: SystemctlReload,
      no_reload: NoReload,
    }
  }

  /// Read the flake's declared caches and put them where Nix will look.
  ///
  /// Order matters and is the whole point: discover, verify, write
  /// `xi.conf`, amend `nix.conf`, record the receipt, reload. Nothing
  /// is written before the key guard has passed, and the receipt is
  /// recorded before the reload so a reload failure still leaves a
  /// reversible machine.
  ///
  /// Takes the sources lock (`ActorName::CachePrestage`) for the whole
  /// call, including the read-only discovery: a build triggered the
  /// moment the write lands would otherwise be able to race it. Released
  /// by `Drop` once this returns. (`BootstrapPlan`'s own `CachePrestage`
  /// phase does not call this yet - see its `apply` arm - so there is no
  /// double-acquisition to worry about from that direction today.)
  ///
  /// # Errors
  ///
  /// See [`PrestageError`]. `Missing` is a status, not an error: a flake
  /// that declares no caches is a normal flake. [`PrestageError::Lock`]
  /// when the sources lock is held by another actor or
  /// `XI_SOURCES_LOCK_WAIT` is unparsable.
  pub fn run(
    &self,
    flake_ref: &str,
    candidates: &[String],
    opts: &PrestageOptions,
  ) -> Result<PrestageReport, PrestageError> {
    let lock_opts =
      LockOptions::from_env(ActorName::CachePrestage, "cache prestage")
        .map_err(PrestageError::Lock)?;
    let _lock = SourcesLock::acquire(&self.lock_state_dir, &lock_opts)
      .map_err(|err| PrestageError::Lock(err.to_string()))?;

    let found = discover(self.reader, flake_ref, candidates)
      .map_err(PrestageError::Reader)?;

    let Some(found) = found else {
      info!(
        "no cache settings declared by {flake_ref} at any of {} well-known \
         attribute paths; nothing to prestage",
        candidates.len()
      );
      return Ok(PrestageReport {
        schema_version:      CACHE_SCHEMA_VERSION,
        status:              PrestageStatus::Missing,
        scope:               self.scope,
        attr_path:           None,
        settings:            CacheSettings::default(),
        paths:               self.paths.clone(),
        amend:               None,
        reloaded:            false,
        trusted_as_declared: Vec::new(),
      });
    };

    let waved_through = self.guard_keys(&found.settings, *opts)?;

    // The receipt is read before anything is written, because its
    // pre-amend hash is the only record of what `nix.conf` looked like
    // before xi ever touched it. Re-deriving it now  -  after a
    // previous run already appended the include line  -  would record
    // the amended file as the original and make unstage a no-op.
    let prior = CacheReceipt::load(&self.paths.receipt)?;
    let before = match prior.as_ref() {
      Some(receipt) => receipt.nix_conf_sha256_before.clone(),
      None => {
        sha256_of_file(&self.paths.nix_conf).map_err(|source| {
          PrestageError::Io {
            path: self.paths.nix_conf.clone(),
            source,
          }
        })?
      },
    };

    let rendered = render_xi_conf(&found.settings);
    let fragment_current = fs::read_to_string(&self.paths.xi_conf)
      .is_ok_and(|on_disk| on_disk == rendered);
    if !fragment_current {
      write_atomic(&self.paths.xi_conf, &rendered).map_err(|source| {
        PrestageError::Io {
          path: self.paths.xi_conf.clone(),
          source,
        }
      })?;
      info!("wrote {}", self.paths.xi_conf.display());
    }

    let (amend, appended) =
      amend_nix_conf(&self.paths.nix_conf).map_err(|source| {
        PrestageError::Io {
          path: self.paths.nix_conf.clone(),
          source,
        }
      })?;

    let changed = !fragment_current || amend == AmendOutcome::Added;

    // Preserve the suffix the *first* run appended. A later run finds
    // the line already present and has nothing of its own to record.
    let appended_suffix = appended
      .or_else(|| prior.as_ref().and_then(|r| r.appended_suffix.clone()));

    if changed || prior.is_none() {
      // Per `xi-sources-crash-recovery`'s receipt-consistency rule: the
      // receipt write runs inside a transaction, and the generic
      // crash-recovery receipt entry - what lets `xi sources repair`
      // tell "this action already happened" from "it was interrupted
      // before its receipt landed" (see `repair::ReceiptEvidence`) -
      // is staged so its append is structurally the last thing that
      // happens before the sentinel comes off. The write-pass above
      // (xi.conf, the `nix.conf` amend) is not staged as a shadow: both
      // already go through `write_atomic`, which is itself crash-safe
      // per file, so this transaction's job is only the sentinel and
      // the receipt ordering, same as `bootstrap`'s per-phase one.
      let mut txn = super::transaction::Transaction::begin(
        &self.lock_state_dir,
        ActorName::CachePrestage.as_str(),
        format!("xi {} sources cache prestage", self.scope),
      )
      .map_err(|source| {
        PrestageError::Io {
          path: self.lock_state_dir.clone(),
          source,
        }
      })?;

      CacheReceipt {
        schema_version: CACHE_SCHEMA_VERSION,
        scope: self.scope,
        nix_conf: self.paths.nix_conf.clone(),
        xi_conf: self.paths.xi_conf.clone(),
        nix_conf_sha256_before: before,
        include_line: INCLUDE_LINE.to_owned(),
        appended_suffix,
        timestamp: now_rfc3339(),
        attr_path: found.attr_path.clone(),
        settings: found.settings.clone(),
      }
      .store(&self.paths.receipt)?;

      // Staged once, not every run: `Transaction::commit` appends
      // unconditionally, and the generic receipt only needs to say
      // once that this action has happened, not carry one entry per
      // invocation of a capability that can legitimately re-run.
      let already_recorded = super::receipt::Receipt::load(&self.lock_state_dir)
        .map_err(|source| {
          PrestageError::Io {
            path: self.lock_state_dir.clone(),
            source,
          }
        })?
        .records(super::repair::WRITE_XI_CONF_ACTION);
      if !already_recorded {
        txn.stage_receipt(super::receipt::ReceiptEntry::new(
          super::repair::WRITE_XI_CONF_ACTION,
        ));
      }

      txn.commit().map_err(|source| {
        PrestageError::Io {
          path: self.lock_state_dir.clone(),
          source,
        }
      })?;
    }

    let reloaded = changed && self.reload_if_needed()?;

    Ok(PrestageReport {
      schema_version: CACHE_SCHEMA_VERSION,
      status: if changed {
        PrestageStatus::Applied
      } else {
        PrestageStatus::Unchanged
      },
      scope: self.scope,
      attr_path: Some(found.attr_path),
      settings: found.settings,
      paths: self.paths.clone(),
      amend: Some(amend),
      reloaded,
      trusted_as_declared: waved_through,
    })
  }

  /// Run the declared-key guard, or announce that it was bypassed.
  fn guard_keys(
    &self,
    settings: &CacheSettings,
    opts: PrestageOptions,
  ) -> Result<Vec<String>, PrestageError> {
    if !opts.trust_declared_keys {
      return verify_keys(settings, self.advertiser)
        .map(|()| Vec::new())
        .map_err(|keys| PrestageError::UnverifiedKeys { keys });
    }

    let waved: Vec<String> = settings
      .trusted_public_keys
      .iter()
      .filter(|key| !BUILTIN_ADVERTISED_KEYS.contains(&key.as_str()))
      .cloned()
      .collect();
    for key in &waved {
      warn!(
        "--trust-declared-keys: adding {key} to trusted-public-keys without \
         verifying it against its substituter"
      );
    }
    Ok(waved)
  }

  /// Reload the daemon when this scope needs it. Returns whether it ran.
  fn reload_if_needed(&self) -> Result<bool, PrestageError> {
    if !scope_needs_reload(self.scope) {
      return Ok(false);
    }
    self.reload.reload().map_err(PrestageError::Reload)?;
    info!("reloaded the nix-daemon so the next build sees the new caches");
    Ok(true)
  }

  /// Reverse a prestage, restoring `nix.conf` byte-for-byte.
  ///
  /// # Errors
  ///
  /// [`PrestageError::NotPrestaged`] with no receipt, and
  /// [`PrestageError::NixConfModified`] when the file no longer hashes
  /// to what the receipt recorded. The second is a refusal, not a
  /// repair: the operator edited `nix.conf` in the interim and xi has
  /// no way to tell their edit from its own.
  pub fn unstage(&self) -> Result<UnstageReport, PrestageError> {
    let Some(receipt) = CacheReceipt::load(&self.paths.receipt)? else {
      return Err(PrestageError::NotPrestaged {
        path: self.paths.receipt.clone(),
      });
    };

    let body = match fs::read_to_string(&receipt.nix_conf) {
      Ok(raw) => raw,
      Err(e) if e.kind() == io::ErrorKind::NotFound => String::new(),
      Err(source) => {
        return Err(PrestageError::Io {
          path: receipt.nix_conf,
          source,
        });
      },
    };

    let restored = remove_include(&body, receipt.appended_suffix.as_deref());
    if sha256_hex(&restored) != receipt.nix_conf_sha256_before {
      return Err(PrestageError::NixConfModified {
        nix_conf: receipt.nix_conf.clone(),
        xi_conf:  receipt.xi_conf,
      });
    }

    let include_removed = restored != body;
    if include_removed {
      if restored.is_empty() && !body.is_empty() {
        // The machine had no nix.conf before the prestage. Leaving an
        // empty file behind would not be byte-identical to that.
        remove_file_if_present(&receipt.nix_conf)?;
      } else {
        write_atomic(&receipt.nix_conf, &restored).map_err(|source| {
          PrestageError::Io {
            path: receipt.nix_conf.clone(),
            source,
          }
        })?;
      }
      info!("restored {}", receipt.nix_conf.display());
    }

    let xi_conf_removed = remove_file_if_present(&receipt.xi_conf)?;
    let reloaded = self.reload_if_needed()?;
    remove_file_if_present(&self.paths.receipt)?;

    Ok(UnstageReport {
      schema_version: CACHE_SCHEMA_VERSION,
      scope: self.scope,
      nix_conf: receipt.nix_conf,
      include_removed,
      xi_conf_removed,
      reloaded,
    })
  }

  /// Report whether a prestage is active and what it put in effect.
  ///
  /// Reads the fragment rather than re-evaluating the flake, so the
  /// answer is what Nix will actually use and not what a fresh eval
  /// would propose.
  ///
  /// # Errors
  ///
  /// Propagates read failures and an unreadable receipt.
  pub fn status(&self) -> Result<CacheStatusReport, PrestageError> {
    let receipt = CacheReceipt::load(&self.paths.receipt)?;

    let fragment = match fs::read_to_string(&self.paths.xi_conf) {
      Ok(raw) => Some(raw),
      Err(e) if e.kind() == io::ErrorKind::NotFound => None,
      Err(source) => {
        return Err(PrestageError::Io {
          path: self.paths.xi_conf.clone(),
          source,
        });
      },
    };

    let include_present = match fs::read_to_string(&self.paths.nix_conf) {
      Ok(raw) => raw.lines().any(|line| line.trim() == INCLUDE_LINE),
      Err(e) if e.kind() == io::ErrorKind::NotFound => false,
      Err(source) => {
        return Err(PrestageError::Io {
          path: self.paths.nix_conf.clone(),
          source,
        });
      },
    };

    let settings = fragment.as_deref().map_or_else(
      || {
        receipt
          .as_ref()
          .map(|r| r.settings.clone())
          .unwrap_or_default()
      },
      parse_xi_conf,
    );

    Ok(CacheStatusReport {
      schema_version: CACHE_SCHEMA_VERSION,
      scope: self.scope,
      active: include_present && fragment.is_some(),
      nix_conf: self.paths.nix_conf.clone(),
      xi_conf: self.paths.xi_conf.clone(),
      include_present,
      xi_conf_present: fragment.is_some(),
      receipt_present: receipt.is_some(),
      settings,
      attr_path: receipt.as_ref().map(|r| r.attr_path.clone()),
      prestaged_at: receipt.map(|r| r.timestamp),
    })
  }
}

/// Owner of the live trait implementations, so [`Prestage`] can borrow
/// them.
///
/// `Prestage` holds references rather than boxes because the test
/// doubles are zero-sized and boxing them would allocate for nothing.
/// Something has to own the live ones; this is that something.
#[derive(Debug)]
pub struct LiveParts {
  scope:          Scope,
  paths:          ConfPaths,
  lock_state_dir: PathBuf,
  reader:         NixAttrReader,
  advertiser:     HttpsKeyAdvertiser,
  systemctl:      SystemctlReload,
  no_reload:      NoReload,
}

impl LiveParts {
  /// Borrow the parts as a [`Prestage`].
  #[must_use]
  pub fn as_prestage(&self) -> Prestage<'_> {
    Prestage {
      scope:          self.scope,
      paths:          self.paths.clone(),
      lock_state_dir: self.lock_state_dir.clone(),
      reader:         &self.reader,
      advertiser:     &self.advertiser,
      reload:         if scope_needs_reload(self.scope) {
        &self.systemctl as &dyn DaemonReload
      } else {
        &self.no_reload as &dyn DaemonReload
      },
    }
  }
}

/// Delete a file, reporting whether there was one. Missing is fine.
fn remove_file_if_present(path: &Path) -> Result<bool, PrestageError> {
  match fs::remove_file(path) {
    Ok(()) => Ok(true),
    Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(false),
    Err(source) => {
      Err(PrestageError::Io {
        path: path.to_path_buf(),
        source,
      })
    },
  }
}

/// Now, RFC 3339, second precision.
fn now_rfc3339() -> String {
  chrono::Utc::now().to_rfc3339_opts(chrono::SecondsFormat::Secs, true)
}

