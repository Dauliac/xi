/// Split a `<flake-ref>[#<attr>]` positional.
///
/// Splits on the *last* `#`, matching how Nix reads an installable: a
/// flake reference can carry a `#` inside a query string, an attribute
/// path cannot.
#[must_use]
pub fn split_target(raw: &str) -> (String, Option<String>) {
  raw.rsplit_once('#').map_or_else(
    || (raw.trim().to_owned(), None),
    |(reference, attr)| {
      (
        reference.trim().to_owned(),
        Some(attr.trim().to_owned()).filter(|a| !a.is_empty()),
      )
    },
  )
}

/// The flake reference to prestage from when the operator names none.
///
/// This scope's managed clone, which is where the configuration xi is
/// about to build already lives. `path:` rather than a bare path so Nix
/// reads it as a flake reference and not as an attribute.
#[must_use]
pub fn default_flake_ref(scope: Scope) -> String {
  format!("path:{}", ScopePaths::resolve(scope).sources_dir.display())
}

/// The attribute paths to probe for `scope`, honouring an override.
///
/// # Errors
///
/// Propagates the hostname lookup failure, since four of the six
/// candidates are keyed on it.
pub fn candidates_for(
  attr_override: Option<String>,
  hostname: Option<String>,
) -> color_eyre::Result<Vec<String>> {
  if let Some(attr) = attr_override {
    return Ok(vec![attr]);
  }
  let host = crate::util::get_hostname(hostname)?;
  let user = std::env::var("USER").unwrap_or_default();
  Ok(candidate_attr_paths(&host, &user))
}
