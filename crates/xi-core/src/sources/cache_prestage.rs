//! The `xi-sources-cache-prestage` capability: teach a machine about its
//! own binary caches *before* it builds anything.
//!
//! Without this, a fresh machine builds every derivation from source,
//! because the substituters the config repo declares only reach
//! `nix.conf` after the first activation has already landed them. The
//! trick, stolen from nixos-anywhere, is that
//! `nix eval --apply toString <ref>#...nix.settings.substituters` is a
//! *pure* evaluation: it reads a static attribute out of the flake
//! without building, so the caches can be configured first and the
//! first build is cache-fast.
//!
//! The capability is three things glued together:
//!
//! - a reader ([`AttrReader`], [`discover`]) that walks a fixed list of
//!   well-known attribute paths and takes the first that evaluates,
//! - a writer ([`render_xi_conf`], [`amend_nix_conf`]) that puts the answer in
//!   its own `xi.conf` and references it from `nix.conf` with a single
//!   `!include` line, so the operator's own file is never edited,
//! - a receipt ([`CacheReceipt`]) that records enough to put `nix.conf` back
//!   byte-for-byte on [`Prestage::unstage`].
//!
//! Every outside effect is behind a trait  -  [`AttrReader`] for `nix
//! eval`, [`KeyAdvertiser`] for the HTTPS key check, [`DaemonReload`]
//! for `systemctl`  -  and every path comes from [`ConfPaths`]. That is
//! not decoration: a test for "writes `/etc/nix/xi.conf` and reloads the
//! daemon" must not write `/etc/nix/xi.conf` or reload the daemon.
//!
//! Two deliberate deviations from
//! `openspec/changes/xi-sources-cache-prestage/specs/xi-sources-cache-prestage/
//! spec.md` are documented at [`candidate_attr_paths`] and
//! [`BUILTIN_ADVERTISED_KEYS`].

