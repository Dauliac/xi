/// The three files this capability touches, for one scope.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ConfPaths {
  /// The operator's own `nix.conf`. xi only ever appends one line.
  pub nix_conf: PathBuf,
  /// The generated fragment. Owned entirely by xi.
  pub xi_conf:  PathBuf,
  /// The reversal receipt.
  pub receipt:  PathBuf,
}

impl ConfPaths {
  /// Resolve the table for `scope` against the process environment.
  #[must_use]
  pub fn resolve(scope: Scope) -> Self {
    Self::resolve_with(scope, &|key| std::env::var(key).ok())
  }

  /// Resolve the table against an arbitrary environment.
  ///
  /// System paths are fixed under [`SYSROOT_ENV`] (default `/`); user
  /// paths follow XDG, including its `$HOME`-relative fallbacks. Taking
  /// the lookup as a closure is what makes both testable without
  /// mutating the process environment, which no parallel test can do
  /// safely.
  #[must_use]
  pub fn resolve_with(
    scope: Scope,
    lookup: &dyn Fn(&str) -> Option<String>,
  ) -> Self {
    match scope {
      Scope::System => {
        let root = lookup(SYSROOT_ENV)
          .filter(|r| !r.is_empty())
          .map(PathBuf::from)
          .filter(|r| r.is_absolute())
          .unwrap_or_else(|| PathBuf::from("/"));
        Self::under(&root.join("etc/nix"), &root.join("var/lib/xi"))
      },
      Scope::User => {
        let nix_dir =
          super::config::xdg_base(lookup, "XDG_CONFIG_HOME", ".config")
            .join("nix");
        let state_dir =
          super::config::xdg_base(lookup, "XDG_STATE_HOME", ".local/state")
            .join("xi");
        Self::under(&nix_dir, &state_dir)
      },
    }
  }

  /// Build the table from the two directories it is derived from.
  ///
  /// The injection point every test uses, and the reason no test has to
  /// go near the real `/etc/nix`.
  #[must_use]
  pub fn under(nix_dir: &Path, state_dir: &Path) -> Self {
    Self {
      nix_conf: nix_dir.join("nix.conf"),
      xi_conf:  nix_dir.join(XI_CONF_NAME),
      receipt:  state_dir.join(RECEIPT_NAME),
    }
  }
}

