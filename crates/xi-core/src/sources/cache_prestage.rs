/// Asks a substituter which public keys it signs with.
pub trait KeyAdvertiser {
  /// The keys `substituter` advertises, over HTTPS.
  ///
  /// # Errors
  ///
  /// Returns a message when the host is unreachable, is not HTTPS, or
  /// advertises nothing. Per spec all three refuse the write, so they
  /// need not be distinguished here.
  fn advertised_keys(&self, substituter: &str) -> Result<Vec<String>, String>;
}

/// A key the guard could not confirm, and why.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct UnverifiedKey {
  /// The key as the flake declared it.
  pub key:    String,
  /// Why it could not be confirmed.
  pub reason: String,
}

impl fmt::Display for UnverifiedKey {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    write!(f, "{}: {}", self.key, self.reason)
  }
}

/// The label part of a `name:base64` public key.
fn key_name(key: &str) -> &str {
  key.split_once(':').map_or(key, |(name, _)| name)
}

/// A key name with its trailing `-<digits>` generation suffix removed.
///
/// `cache.nixos.org-1` names the host `cache.nixos.org`; the `-1` is a
/// rotation counter, not part of the identity.
fn key_base(key: &str) -> &str {
  let name = key_name(key);
  name
    .rsplit_once('-')
    .filter(|(_, tail)| {
      !tail.is_empty() && tail.bytes().all(|b| b.is_ascii_digit())
    })
    .map_or(name, |(base, _)| base)
}

/// Whether `substituter`'s URL claims the identity `base` names.
///
/// Matches the URL host (`https://cache.example.org` for
/// `cache.example.org-1`) or any path segment (`https://attic.example
/// .com/mycache` for `mycache-1`), which covers the cache-per-path
/// servers as well as the cache-per-host ones.
fn substituter_claims(substituter: &str, base: &str) -> bool {
  let rest = substituter
    .split_once("://")
    .map_or(substituter, |(_, rest)| rest);
  let mut parts = rest.split('/');
  let Some(host) = parts.next() else {
    return false;
  };
  let host = host.split_once('@').map_or(host, |(_, h)| h);
  let host = host.split_once(':').map_or(host, |(h, _)| h);
  host == base || parts.any(|segment| segment == base)
}

/// Verify every declared key against the host of its own substituter.
///
/// A key xi cannot tie back to a substituter is as unverifiable as one
/// whose host denies it: adding it to `trusted-public-keys` would make
/// it a code-signing authority for everything the machine builds
/// afterwards, with nothing having vouched for it.
///
/// # Errors
///
/// Returns every key that could not be confirmed. The caller writes
/// nothing in that case.
pub fn verify_keys(
  settings: &CacheSettings,
  advertiser: &dyn KeyAdvertiser,
) -> Result<(), Vec<UnverifiedKey>> {
  // One fetch per substituter, not one per key: the common case is
  // several keys from one host mid-rotation.
  let mut fetched: BTreeMap<&str, Result<Vec<String>, String>> =
    BTreeMap::new();
  let mut unverified = Vec::new();

  for key in &settings.trusted_public_keys {
    if BUILTIN_ADVERTISED_KEYS.contains(&key.as_str()) {
      debug!("{key} is a Nix built-in trusted key; no fetch needed");
      continue;
    }

    let base = key_base(key);
    let Some(substituter) = settings
      .substituters
      .iter()
      .find(|s| substituter_claims(s, base))
    else {
      unverified.push(UnverifiedKey {
        key:    key.clone(),
        reason: format!(
          "no declared substituter claims '{base}', so there is no host that \
           could vouch for it"
        ),
      });
      continue;
    };

    let advertised = fetched
      .entry(substituter.as_str())
      .or_insert_with(|| advertiser.advertised_keys(substituter));

    match advertised {
      Err(reason) => {
        unverified.push(UnverifiedKey {
          key:    key.clone(),
          reason: format!("{substituter}: {reason}"),
        });
      },
      Ok(keys) if keys.contains(key) => {},
      Ok(_) => {
        unverified.push(UnverifiedKey {
          key:    key.clone(),
          reason: format!("{substituter} does not advertise this key"),
        });
      },
    }
  }

  if unverified.is_empty() {
    Ok(())
  } else {
    Err(unverified)
  }
}

/// The real advertiser: HTTPS to the substituter's own host.
///
/// There is no entry in the binary-cache protocol for "tell me your
/// public keys"  -  `nix-cache-info` carries a store dir and a priority
/// and nothing else  -  so this probes the two endpoints the hosted
/// caches actually serve (Cachix's `/api/v1/cache/<name>` and Attic's
/// `/_api/v1/cache-config/<name>`) and treats a cache that answers
/// neither as unverifiable. That is the honest outcome, and it is
/// exactly what `--trust-declared-keys` exists for.
#[derive(Debug, Clone, Copy, Default)]
pub struct HttpsKeyAdvertiser;

impl KeyAdvertiser for HttpsKeyAdvertiser {
  fn advertised_keys(&self, substituter: &str) -> Result<Vec<String>, String> {
    let url = substituter.trim_end_matches('/');
    if !url.starts_with("https://") {
      return Err(
        "only an https:// substituter can vouch for its own keys".to_owned(),
      );
    }

    let client = reqwest::blocking::Client::builder()
      .timeout(KEY_FETCH_TIMEOUT)
      .build()
      .map_err(|e| format!("could not build an HTTPS client: {e}"))?;

    // Prove the host really is a binary cache before trusting anything
    // it says about keys.
    let info = client
      .get(format!("{url}/nix-cache-info"))
      .send()
      .map_err(|e| format!("unreachable: {e}"))?;
    if !info.status().is_success() {
      return Err(format!(
        "no nix-cache-info (HTTP {})",
        info.status().as_u16()
      ));
    }

    let name = url.rsplit('/').next().unwrap_or_default();
    let origin = url.split_once("://").map_or_else(
      || url.to_owned(),
      |(scheme, rest)| {
        let host = rest.split('/').next().unwrap_or(rest);
        format!("{scheme}://{host}")
      },
    );
    let host_label = origin
      .trim_start_matches("https://")
      .split('.')
      .next()
      .unwrap_or_default()
      .to_owned();

    let mut keys = Vec::new();
    for (base, cache) in [
      (origin.as_str(), name),
      (origin.as_str(), host_label.as_str()),
    ] {
      if cache.is_empty() {
        continue;
      }
      for path in [
        format!("{base}/api/v1/cache/{cache}"),
        format!("{base}/_api/v1/cache-config/{cache}"),
      ] {
        if let Some(found) = advertised_from(&client, &path) {
          keys.extend(found);
        }
      }
      if !keys.is_empty() {
        break;
      }
    }

    keys.sort_unstable();
    keys.dedup();
    if keys.is_empty() {
      return Err(
        "advertises no public keys over HTTPS (pass --trust-declared-keys to \
         accept the flake's own list)"
          .to_owned(),
      );
    }
    Ok(keys)
  }
}

/// `publicSigningKeys` from one cache-metadata endpoint, if it answers.
fn advertised_from(
  client: &reqwest::blocking::Client,
  url: &str,
) -> Option<Vec<String>> {
  let body = client.get(url).send().ok()?;
  if !body.status().is_success() {
    return None;
  }
  let json: serde_json::Value = body.json().ok()?;
  let keys = json
    .get("publicSigningKeys")
    .or_else(|| json.get("public_signing_keys"))?
    .as_array()?
    .iter()
    .filter_map(|v| v.as_str().map(str::to_owned))
    .collect::<Vec<_>>();
  (!keys.is_empty()).then_some(keys)
}

