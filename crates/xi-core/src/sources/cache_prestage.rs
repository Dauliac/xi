/// Why a prestage or unstage could not be completed.
#[derive(Debug, thiserror::Error)]
pub enum PrestageError {
  /// The flake could not be read at all (no `nix`, impure input, ...).
  /// Distinct from "the flake declares no caches", which is `Missing`.
  #[error("could not read the flake's cache settings: {0}")]
  Reader(String),

  /// At least one declared key could not be tied to a host that vouches
  /// for it. Nothing was written.
  #[error(
    "refusing to prestage {} unverifiable signing key(s):\n  {}\n\nAdding a \
     key to trusted-public-keys makes it a code-signing authority for \
     everything this machine builds afterwards. Pass \
     --trust-declared-keys to accept the flake's own list.",
    keys.len(),
    keys.iter().map(ToString::to_string).collect::<Vec<_>>().join("\n  ")
  )]
  UnverifiedKeys {
    /// Every key that could not be confirmed, with its reason.
    keys: Vec<UnverifiedKey>,
  },

  /// `xi sources cache unstage` with nothing to reverse.
  #[error(
    "no cache prestage to reverse: {} does not exist",
    path.display()
  )]
  NotPrestaged {
    /// Where the receipt would have been.
    path: PathBuf,
  },

  /// `nix.conf` is not what the receipt says it was, so removing the
  /// include line would not restore it.
  #[error(
    "{} has changed since the prestage; refusing to unstage.\n\nRemove the \
     `{INCLUDE_LINE}` line and {} by hand if that is what you want.",
    nix_conf.display(),
    xi_conf.display()
  )]
  NixConfModified {
    /// The file that no longer matches the receipt.
    nix_conf: PathBuf,
    /// The fragment that would have been deleted.
    xi_conf:  PathBuf,
  },

  /// The receipt exists but is not a receipt this xi understands.
  #[error("{}: {source}", path.display())]
  Receipt {
    /// The unreadable receipt.
    path:   PathBuf,
    /// The underlying failure.
    #[source]
    source: serde_json::Error,
  },

  /// A file could not be read or written.
  #[error("{}: {source}", path.display())]
  Io {
    /// The file involved.
    path:   PathBuf,
    /// The underlying failure.
    #[source]
    source: io::Error,
  },

  /// The write landed but the daemon would not re-read it, so the next
  /// build would still use the old substituters.
  #[error("cache config written, but the nix-daemon reload failed: {0}")]
  Reload(String),

  /// The sources lock could not be acquired: another actor holds it, or
  /// `XI_SOURCES_LOCK_WAIT` is unparsable.
  #[error("{0}")]
  Lock(String),
}

