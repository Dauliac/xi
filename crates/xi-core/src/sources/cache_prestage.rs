/// Makes a running nix-daemon re-read its configuration.
pub trait DaemonReload {
  /// Reload, or explain why not.
  ///
  /// # Errors
  ///
  /// Returns a message when the reload could not be performed.
  fn reload(&self) -> Result<(), String>;
}

/// `systemctl reload nix-daemon`.
#[derive(Debug, Clone, Copy, Default)]
pub struct SystemctlReload;

impl DaemonReload for SystemctlReload {
  fn reload(&self) -> Result<(), String> {
    let output = Command::new("systemctl")
      .args(["reload", "nix-daemon"])
      .output()
      .map_err(|e| format!("could not run systemctl: {e}"))?;
    if output.status.success() {
      return Ok(());
    }
    Err(format!(
      "systemctl reload nix-daemon failed: {}",
      String::from_utf8_lossy(&output.stderr).trim()
    ))
  }
}

/// The user-scope reloader: there is nothing to reload.
///
/// Nix reads `~/.config/nix/nix.conf` once per invocation, so the next
/// `nix build` already sees the new substituters.
#[derive(Debug, Clone, Copy, Default)]
pub struct NoReload;

impl DaemonReload for NoReload {
  fn reload(&self) -> Result<(), String> {
    debug!("user scope needs no daemon reload");
    Ok(())
  }
}

/// Whether `scope` needs a daemon reload for a write to take effect.
#[must_use]
pub const fn scope_needs_reload(scope: Scope) -> bool {
  matches!(scope, Scope::System)
}

