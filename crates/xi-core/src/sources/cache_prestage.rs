/// Wire version of the receipt and of the `cache status` envelope.
pub const CACHE_SCHEMA_VERSION: u32 = 1;

/// The one line xi is allowed to add to the operator's `nix.conf`.
///
/// The leading `!` is load-bearing: in `nix.conf` it means
/// "include this file *if it exists*". That is what lets
/// [`Prestage::unstage`] delete `xi.conf` without having to also remove
/// the line in the case where the line was already there before xi ran.
pub const INCLUDE_LINE: &str = "!include xi.conf";

/// Name of the generated fragment, in the same directory as `nix.conf`.
pub const XI_CONF_NAME: &str = "xi.conf";

/// Name of the reversal receipt.
pub const RECEIPT_NAME: &str = "cache-receipt.json";

/// First line of the generated fragment, so nobody mistakes it for
/// something they wrote.
const XI_CONF_HEADER: &str = "# generated by xi sources cache prestage";

/// Re-root for the system-scope paths, for tests and offline images.
///
/// Env-only, like [`super::config::STATE_DIR_ENV`], and for the same
/// reason: a repo-committed `.xi.toml` must not be able to redirect
/// where xi writes `nix.conf`. Only an absolute path is honoured.
pub const SYSROOT_ENV: &str = "XI_NIX_SYSROOT";

/// Keys that need no HTTPS check because Nix itself already trusts them.
///
/// `cache.nixos.org-1` is compiled into every Nix as a default
/// `trusted-public-keys` entry, so accepting it here grants no trust
/// that the machine did not already have. Without this the guard would
/// refuse the single most common declaration in existence  -  a flake
/// that lists `cache.nixos.org` alongside its own cache  -  and every
/// operator would learn to reach for `--trust-declared-keys`, which is
/// the opposite of what the guard is for.
pub const BUILTIN_ADVERTISED_KEYS: &[&str] =
  &["cache.nixos.org-1:6NCHdD59X431o0gWypbMrAURkbJ16ZPMQFGspcDShjY="];

/// How long the key check waits on a substituter host.
const KEY_FETCH_TIMEOUT: Duration = Duration::from_secs(10);

